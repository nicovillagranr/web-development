/**
 * LOS DATOS DEL REPORTE, TAL COMO VIENEN.
 *
 * Esta es la capa **RAW** del §16: la tabla del reporte de Picker Performance
 * transcrita con sus columnas originales y en su orden original, sin traducir, sin
 * reagrupar y sin juzgar. La única transformación aplicada es la mínima que exige
 * TypeScript: `"1,32%"` pasó a `1.32` y `"-"` pasó a `null`. Nada más.
 *
 * Todo lo demás —renombrar columnas, decidir unidades, evaluar contra objetivos—
 * ocurre en las capas de encima. Es la separación que pide el §14 y el motivo de
 * que este archivo no importe absolutamente nada.
 *
 * ── Por qué los nombres NO son los del local ─────────────────────────────────
 * Las cifras son las del reporte real. Los nombres no: son de relleno, y viven
 * emparejados por posición con las filas de abajo. Los reales, si existen, están
 * en `roster.private.ts`, que git ignora y que `roster.ts` sólo consulta en
 * desarrollo. El §20 es explícito: los datos reales no entran al repositorio.
 *
 * Queda un riesgo residual que conviene tener escrito y no descubrir después:
 * quien tenga el reporte original puede volver a emparejar estas cifras con sus
 * nombres, porque son las mismas cifras. Es un intercambio deliberado —la demo
 * conserva la textura real de los datos— y no una anonimización a prueba de todo.
 * Si algún día el repositorio deja de ser un portfolio, hay que sacudir los
 * números además de los nombres.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Dos columnas llegan **enteras a null** (`rating` y `ausencias`) y otras dos
 * llegan vacías en 25 de 30 filas (`totalTask`, `taskDurationMin`). Se conservan a
 * propósito: la capa RAW registra lo que el documento traía, no lo que a la app le
 * sirve. Que una columna venga vacía es justamente el tipo de hecho que el
 * validador del §15 tiene que poder comprobar.
 */

