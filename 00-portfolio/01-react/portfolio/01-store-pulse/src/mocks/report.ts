export type ReportColumn = (typeof REPORT_COLUMNS)[number];

/**
 * Una celda del reporte. `null` es la celda "-": sin dato. **Nunca cero.**
 *
 * Confundir los dos es el error que pinta de rojo a quien todavía no tiene datos, y
 * es justo lo que el §15 manda evitar.
 */
type Cell = number | null;

/**
 * Convierte la tupla de columnas en una tupla de celdas de la MISMA longitud.
 *
 * Es un *mapped type* aplicado sobre una tupla, y ahí está el truco: al mapear una
 * tupla, TypeScript conserva su longitud en vez de degradarla a array. Así `Cells`
 * no significa "algunas celdas" sino "exactamente tantas celdas como columnas haya",
 * sin que el número 20 aparezca escrito en ningún sitio.
 */
type Cells<T extends readonly unknown[]> = { readonly [K in keyof T]: Cell };

/**
 * Una fila del reporte: el nombre y sus valores, en el orden de `REPORT_COLUMNS`.
 *
 * Es una tupla y no un objeto por dos motivos. El primero es que así la tabla se lee
 * como una tabla: columnas alineadas, treinta filas, y los huecos se ven de un
 * vistazo. El segundo es el que de verdad importa: **la longitud la comprueba el
 * compilador**. Si mañana el reporte trae una columna más y se añade a
 * `REPORT_COLUMNS` sin tocar las filas, las treinta se quedan cortas y esto deja de
 * compilar. El descuadre aparece en el build, no en pantalla como una columna
 * corrida un puesto — que es el fallo que nadie ve hasta que ya tomó una decisión.
 */
export type ReportRow = readonly [name: string, ...Cells<typeof REPORT_COLUMNS>];

